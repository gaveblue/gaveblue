// GB+ 2.7.3 — preferência de período e navegação do formulário.
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {resolve,dirname} from 'node:path';
import {fileURLToPath} from 'node:url';
const here=dirname(fileURLToPath(import.meta.url));
const preference=readFileSync(resolve(here,'../js/period-preference.js'),'utf8');
const {readPeriodPreference,writePeriodPreference}=Function(preference.replace(/^export /gm,'')+';return {readPeriodPreference,writePeriodPreference};')();
const saved=new Map(),storage={getItem:k=>saved.get(k)||null,setItem:(k,v)=>saved.set(k,v)};
assert.equal(readPeriodPreference(storage,'u1'),null);
assert(writePeriodPreference(storage,'u1',{period:'month'}));
assert.equal(readPeriodPreference(storage,'u1').period,'month');
assert.equal(readPeriodPreference(storage,'u2'),null);
assert(writePeriodPreference(storage,'u1',{period:'all'}));
assert.equal(readPeriodPreference(storage,'u1').period,'all');
const range={from:'2026-09-01',to:'2026-10-31'};
assert(writePeriodPreference(storage,'u1',{period:'custom',range}));
assert.deepEqual(readPeriodPreference(storage,'u1'),{period:'custom',range});
assert(!writePeriodPreference(storage,'u1',{period:'custom',range:{from:'2026-13-01',to:'2026-10-31'}}));
saved.set('gbplus-period-v1:u2','{invalid');
assert.equal(readPeriodPreference(storage,'u2'),null);
const app=readFileSync(resolve(here,'../js/app.js'),'utf8');
const css=readFileSync(resolve(here,'../bottom-sheet.css'),'utf8');
assert(app.includes('function mountEntryHeaderActions()'));
assert(app.includes("submit.setAttribute('form',form.id)"));
assert(app.includes("el.closest('#title-form')||modal.querySelector('#title-form')"));
assert(app.includes("const footer=modal.querySelector("));
assert(app.includes("state.period=savedPeriod?.period||'all'"));
assert(app.includes("savePeriodPreference();state.launchSelected=[]"));
assert(css.includes('gb-entry-header-actions')&&css.includes('height:min(575px,88dvh)'));
console.log('GB+ 2.7.3: preferências de período e navegação compacta verificadas.');
