// GB+ 3.0.5: garante dois anéis mínimos e sem efeitos pesados.
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {resolve,dirname} from 'node:path';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const read=p=>readFileSync(resolve(root,p),'utf8');
const html=read('index.html'), css=read('splash.css'),sw=read('sw.js'),v=JSON.parse(read('version.json'));
assert.equal(v.version,'3.0.5');
assert.equal(v.build,3005);
assert(html.includes('content="3.0.5"'));
assert(html.includes('splash.css?v=20261110-3005'));
assert(html.includes('Versão 3.0.5'));
assert(html.includes('id="gb-splash-start">Iniciar</button>'));
assert(html.includes('id="auth-gate"'));
assert(html.includes('src="./js/app.js?v=20261109-3000"'));
assert(html.includes('class="gbintro-orbit" aria-hidden="true"'));
assert(html.includes('class="gbintro-orbit-secondary" aria-hidden="true"'));
assert.equal((html.match(/class="gbintro-orbit" aria-hidden="true"/g)||[]).length,1);
assert.equal((html.match(/class="gbintro-orbit-secondary" aria-hidden="true"/g)||[]).length,1);
assert(!/gbintro-orbit-(?:trace|comet|fore)/.test(html+css));
assert(!/conic-gradient|gbintro-orbitSpin|-webkit-mask:radial-gradient/.test(css));
assert(css.includes('border:1px solid rgba(90,129,198,.27)'));
assert(css.includes('border-color:rgba(100,132,181,.18)'));
assert(css.includes('gbintro-orbitClockwise 18s linear infinite'));
assert(css.includes('gbintro-orbitCounter 25s linear infinite'));
assert(css.includes('background:#fff;color:#152034'));
assert(css.includes('width:min(90vw,390px)'));
assert(css.includes('prefers-reduced-motion:reduce'));
assert(css.includes('gbintro-orbit-secondary {animation:none!important'));
assert(css.includes('.gbintro-loading-label .gbintro-count'));
assert.equal((css.match(/{/g)||[]).length,(css.match(/}/g)||[]).length);
assert(sw.includes('gb-plus-shell-v3005'));
assert(v.assets.includes('./splash.css'));
console.log('GB+ 3.0.5: testes estruturais dos anéis minimalistas passaram.');
