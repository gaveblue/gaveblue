// GB+ 3.0.3 — verifica isolamento e correções visuais da abertura.
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {resolve, dirname} from 'node:path';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const read=path=>readFileSync(resolve(root,path),'utf8');
const html=read('index.html'),css=read('splash.css'),sw=read('sw.js');
const version=JSON.parse(read('version.json'));
assert.equal(version.version,'3.0.3');
assert.equal(version.build,3003);
assert(html.includes('content="3.0.3"'));
assert(html.includes('splash.css?v=20261110-3003'));
assert(html.includes('Versão 3.0.3'));
assert(html.includes('id="gb-splash-start">Iniciar</button>'));
assert(!html.includes('Pular abertura')&&!html.includes('↻ Rever'));
assert(html.includes('id="auth-gate"'));
assert(html.includes('src="./js/app.js?v=20261109-3000"'));
assert(css.includes('.gbintro-plus-box')&&css.includes('margin-left:-6px;'));
assert(css.includes('gap:2px;height:160px;'));
assert(css.includes('gbintro-orbitFloat 12s 3.25s ease-in-out infinite alternate'));
assert(css.includes('gbintro-orbitPulse 7s 3.25s ease-in-out infinite'));
assert(css.includes('@keyframes gbintro-orbitFloat'));
assert(css.includes('@keyframes gbintro-orbitPulse'));
assert(css.includes('.gbintro-loading-label {'));
assert(css.includes('.gbintro-loading-label > span:first-child'));
assert(css.includes('.gbintro-loading-label .gbintro-count'));
assert(css.includes('margin-left:12px'));
assert(css.includes('width:min(320px,calc(100vw - 48px))'));
assert(!css.includes('gbintro-gbintro-'));
assert(css.includes('www.w3.org/2000/svg'));
assert(css.includes('@media (prefers-reduced-motion:reduce)'));
assert(!/^\s*(?:html|body|:root|\*)\s*\{/m.test(css));
assert.equal((css.match(/\{/g)||[]).length,(css.match(/\}/g)||[]).length);
assert(sw.includes('gb-plus-shell-v3003'));
assert(version.assets.includes('./splash.css'));
console.log('GB+ 3.0.3: regressão estática da abertura aprovada.');
