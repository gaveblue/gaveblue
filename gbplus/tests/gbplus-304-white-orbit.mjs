// GB+ 3.0.4 — regressão estática da abertura branca com órbita real.
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {resolve,dirname} from 'node:path';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const read=p=>readFileSync(resolve(root,p),'utf8');
const html=read('index.html'), css=read('splash.css'), sw=read('sw.js');
const v=JSON.parse(read('version.json'));
assert.equal(v.version,'3.0.4');
assert.equal(v.build,3004);
assert(html.includes('content="3.0.4"'));
assert(html.includes('splash.css?v=20261110-3004'));
assert(html.includes('Versão 3.0.4'));
assert(html.includes('id="gb-splash-start">Iniciar</button>'));
assert(!html.includes('Pular abertura')&&!html.includes('↻ Rever'));
assert(html.includes('id="auth-gate"'));
assert(html.includes('src="./js/app.js?v=20261109-3000"'));
assert(html.includes('<span class="gbintro-orbit" aria-hidden="true">'));
assert(html.includes('gbintro-orbit-trace'));
assert(html.includes('gbintro-orbit-comet'));
assert(html.includes('gbintro-orbit-fore'));
assert(html.indexOf('class="gbintro-orbit"')>html.indexOf('class="gbintro-wordmark"'));
assert(css.includes('background:#fff;color:#152034'));
assert(css.includes('color:#152034; transform:translateY'));
assert(css.includes('gbintro-orbitSpin 13s linear infinite'));
assert(css.includes('@keyframes gbintro-orbitSpin'));
assert(css.includes('rotate(344deg)'));
assert(css.includes('clip-path:inset(50% 0 0)'));
assert(css.includes('-webkit-mask:radial-gradient'));
assert(css.includes('width:min(98vw,470px)'));
assert(css.includes('.gbintro-loading-label .gbintro-count'));
assert(css.includes('animation:none!important'));
assert(css.includes('@media (prefers-reduced-motion:reduce)'));
assert.equal((css.match(/{/g)||[]).length,(css.match(/}/g)||[]).length);
assert(!/^\s*(?:html|body|:root|\*)\s*\{/m.test(css));
assert(sw.includes('gb-plus-shell-v3004'));
assert(v.assets.includes('./splash.css'));
console.log('GB+ 3.0.4: checks de abertura branca e órbita dinâmica passaram.');
