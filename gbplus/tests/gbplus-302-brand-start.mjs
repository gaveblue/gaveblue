// GB+ 3.0.2 — regressão estrutural da abertura de produção (sem dados).
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {resolve,dirname} from 'node:path';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const read=p=>readFileSync(resolve(root,p),'utf8');
const html=read('index.html'),css=read('splash.css'),sw=read('sw.js');
const release=JSON.parse(read('version.json'));
const check=(value,label)=>assert.ok(value,label);
assert.equal(release.version,'3.0.2');
assert.equal(release.build,3002);
check(html.includes('content="3.0.2"'),'Meta versionada');
check(html.includes('splash.css?v=20261110-3002'),'CSS cache-busted');
check(html.includes('Versão 3.0.2'),'Rodapé versionado');
check(html.indexOf('id="gb-splash"')<html.indexOf('id="auth-gate"'),'Splash vem antes do login');
check(html.includes('id="gb-splash-start">Iniciar</button>'),'Iniciar é o único botão da abertura');
assert.equal((html.match(/id="gb-splash-start"/g)||[]).length,1);
check(!/Pular abertura|↻ Rever|id="replay"|id="skip"|02-tela-estatica\.html/.test(html),'Sem controles ou destinos do laboratório');
check(html.includes("start.addEventListener('click'"),'Evento de Iniciar presente');
check(html.includes('splash.remove()'),'Ao iniciar, remove sobreposição');
check(html.includes('const callback'),'Callbacks de autenticação preservados');
check(html.includes('const deepLink'),'Links diretos preservados');
check(html.includes("prefers-reduced-motion: reduce"),'Suporte JS a redução de movimento');
check(html.includes('id="auth-gate"'),'Login preservado');
check(html.includes('src="./js/app.js?v=20261109-3000"'),'Aplicativo financeiro preservado');
check(css.includes('.gbintro-letter-wrap'),'Recorte das letras isolado');
check(css.includes('.gbintro-letter')&&css.includes('.gbintro-plus-box'),'Brand Reveal completo');
check(css.includes('#gb-splash-start'),'Botão da abertura estilizado');
check(css.includes('#gb-splash *::after'),'Redução de movimento limitada à abertura');
check(!/^\s*(?:body|html|:root|\*)\s*\{/m.test(css),'CSS não alcança o site inteiro');
check(!/\@import\b/.test(css),'Sem estilos remotos');
assert.equal((css.match(/\{/g)||[]).length,(css.match(/\}/g)||[]).length,'Chaves do CSS balanceadas');
check(sw.includes("gb-plus-shell-v3002"),'Cache do service worker atualizado');
check(release.assets.includes('./splash.css'),'Arquivo listado no manifesto');
console.log('GB+ 3.0.2: 26 verificações da abertura, do login e do isolamento passaram.');
