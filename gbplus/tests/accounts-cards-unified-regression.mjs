// GB+ 2.5.1 — Unificação visual de Contas e Cartões sem alterar dados.
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {resolve,dirname} from 'node:path';
import {fileURLToPath} from 'node:url';

const dir=dirname(fileURLToPath(import.meta.url));
const src=name=>readFileSync(resolve(dir,'../js/'+name),'utf8');
const db={accounts:[{id:'bank1',name:'Conta teste',initial:580000}],cards:[{id:'card1',name:'Cartão teste',limit:100000}],titles:[],payments:[],transfers:[]};
const before=JSON.stringify(db);
const calls=[];
const heading=(title,subtitle,actions)=>'<div class="page-heading"><h1>'+title+'</h1><p>'+subtitle+'</p>'+actions+'</div>';
const accountsView=(data,opts)=>{assert.equal(data,db);assert.equal(opts.embedded,true);calls.push('accounts');return '<div class="account-grid"><article>Conta teste</article></div>';};
const cardsView=(data,opts)=>{assert.equal(data,db);assert.equal(opts.embedded,true);calls.push('cards');return '<div class="gb-credit-grid"><article>Cartão teste</article></div>';};
const button=(label,action)=>'<button data-action="'+action+'">'+label+'</button>';
const icon=name=>'<span data-icon="'+name+'"></span>';
const moduleCode=src('accounts-cards-view.js').replace(/^import[^\n]*\n/gm,'').replace(/^export /gm,'');
const {accountsCardsView}=Function('heading','accountsView','cardsView','button','icon',
 moduleCode+';return {accountsCardsView};')(heading,accountsView,cardsView,button,icon);
const viewAccounts=accountsCardsView(db,'accounts');
assert.match(viewAccounts,/<h1>Contas<\/h1>/);
assert.match(viewAccounts,/role="tablist"/);
assert.match(viewAccounts,/data-tab="accounts"/);
assert.match(viewAccounts,/data-tab="cards"/);
assert.match(viewAccounts,/id="gb-finance-tab-accounts"/);
assert.match(viewAccounts,/aria-selected="true"/);
assert.match(viewAccounts,/role="tabpanel"/);
assert.match(viewAccounts,/Conta teste/);
assert(!viewAccounts.includes('Cartão teste'));
assert.match(viewAccounts,/data-action="new-account"/);
assert.match(viewAccounts,/data-action="new-transfer"/);
assert.match(viewAccounts,/data-action="open-banks"/);
const viewCards=accountsCardsView(db,'cards');
assert.match(viewCards,/<h1>Cartões<\/h1>/);
assert.match(viewCards,/Cartão teste/);
assert(!viewCards.includes('Conta teste'));
assert.match(viewCards,/data-action="new-card"/);
assert.match(viewCards,/id="gb-finance-tab-cards"/);
assert.match(viewCards,/aria-labelledby="gb-finance-tab-cards"/);
assert(!viewCards.includes('data-action="new-account"'));
assert.deepEqual(calls,['accounts','cards']);
assert.equal(JSON.stringify(db),before,'Changing tab must not modify financial records');
assert.equal(accountsCardsView(db,'invalid'),viewAccounts,'Unknown tab defaults safely to accounts');
const routes=src('views.js');
assert.match(routes,/\['accounts','Contas e cartões','wallet'\]/);
assert(!routes.includes("['cards','Cartões de crédito','credit-card']"),'No separate main route for cards');
assert.match(routes,/export function accountsView\(db,\{embedded=false\}=\{\}\)/);
const cards=src('finance-24-ui.js');
assert.match(cards,/export function cardsView\(db,\{embedded=false\}=\{\}\)/);
assert.match(cards,/Faturas/);
assert.match(cards,/Compras recentes/);
const app=src('app.js');
assert.match(app,/accounts:\(\)=>accountsCardsView\(db,state.accountCardsTab\)/);
assert.match(app,/requested==='cards'\?'accounts':requested/,'Legacy #cards link must open unified page');
assert.match(app,/state.accountCardsTab='cards'/);
assert.match(app,/'accounts-cards-tab':el=>/);
assert.match(app,/location.hash='accounts'/);
assert.match(app,/\['ArrowLeft','ArrowRight','Home','End'\]/,'Keyboard navigation is available');
console.log('GB+ 2.5.1: abas, atalhos antigos, acessibilidade, conteúdo e integridade OK.');
